def glyph_rows16(ch):
    """16 ints (bit0 = leftmost of 5 cols) for a char, placed rows 3..13."""
    pat = F.get(ch, F['?'])
    rows = [0]*16
    for i, line in enumerate(pat):
        y = 3 + i
        if y > 15: break
        bits = 0
        for x, c in enumerate(line):
            if c == '#':
                bits |= 1 << x
        rows[y] = bits
    return rows


def _width(ch):
    return max(len(r) for r in F.get(ch, F['?']))


def pair_glyph(a, b):
    """Two chars in one 16x16 1bpp glyph, 32 bytes big-endian rows.
    A starts col 1 (col 0 if 7px wide); B starts col 9. Engine bold +1 right.
    Bit 15 of each row halfword = leftmost pixel (per rasterizer)."""
    ra, rb = glyph_rows16(a), glyph_rows16(b)
    abase = 0 if _width(a) >= 7 else 1
    out = bytearray()
    for y in range(16):
        row = 0
        for x in range(7):
            if ra[y] & (1 << x):
                row |= 0x8000 >> (abase + x)
            if rb[y] & (1 << x) and 9 + x <= 15:
                row |= 0x8000 >> (9 + x)
        out += bytes([row >> 8, row & 0xFF])
    return bytes(out)
